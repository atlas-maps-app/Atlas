#!/usr/bin/env python3
"""Writes the text module's generated tables (K13), run from mapcore/cpp: python3 -I text/tables.py

- text/Uppercase.inc: CPython's str.upper() (the Python of the reference renders, 3.9: Unicode 13.0, as JDK 17's
  String.uppercase(), which :mapcorecheck's TextParityTest holds it to), as runs of single code points and the special
  cases that map to more than one.
- text/CheckRuns.inc: the style and text of every row of tests/text/android_shaping.txt, in its order, which the
  device's glyph check shapes (VK facts); tests/text/shaper_test.cpp holds it to the file.
- text/Digits.inc: the decimal digits (Nd) of the Basic Multilingual Plane, as the zero of each run of ten: what the
  port's runway ends read as a designator's number (Java's Character.isDigit on each UTF-16 unit, Unicode 13.0 on
  JDK 17, as CPython 3.9's \\d within the BMP).
- text/Case.inc: what text/Case.cpp's capitalize() needs to be the port's str.capitalize() (PoiStyle's: Java's
  Character.toTitleCase of the first code point, Kotlin's lowercase() of the rest), from CPython 3.9 (Unicode 13.0, as
  JDK 17): str.lower() of each code point as runs and the special case that maps to more than one; the simple
  titlecase (a code point's str.title() where that is one code point: where it is more, as for ß, Java's simple
  mapping keeps the code point); and the code points Java's final sigma counts as cased (Lu, Ll and Lt, and the
  ranges of Other_Lowercase and Other_Uppercase its ConditionalSpecialCasing lists). :mapcorecheck's CaseParityTest
  holds them to Java's own over every code point.
- text/PyRe.inc: what CPython 3.9's re (Unicode 13.0) reads as \\w, str.isalnum() or "_", as ranges of code points;
  and as \\d beyond the Basic Multilingual Plane, as the zero of each run of ten (text/Digits.inc holds the plane's):
  real.py's opening hours read \\b and \\d over every plane (style/OpeningHours.cpp), as Python does.
"""
import re
import sys
import unicodedata


def runs_of(simple):
    """Runs of (code point, mapping) pairs, ascending: each start + k * stride (k < count) maps to itself + delta."""
    runs, i = [], 0
    while i < len(simple):
        c, u = simple[i]
        d, j, stride = u - c, i + 1, None
        while j < len(simple):
            c2, u2 = simple[j]
            if u2 - c2 != d:
                break
            s = c2 - simple[j - 1][0]
            if stride is None:
                if s > 2:
                    break
                stride = s
            elif s != stride:
                break
            j += 1
        runs.append((c, j - i, stride or 1, d))
        i = j
    return runs


def uppercase():
    simple, special = [], []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        u = chr(c).upper()
        if u == chr(c):
            continue
        if len(u) == 1:
            simple.append((c, ord(u)))
        else:
            special.append((c, [ord(x) for x in u]))
    runs = runs_of(simple)
    out = ["// Generated by text/tables.py from CPython %s (Unicode %s): str.upper(). Do not edit." % (
        sys.version.split()[0], unicodedata.unidata_version),
           "// Each run maps start + k * stride (k < count) to itself + delta; each special case to two or three code "
           "points.",
           "inline constexpr std::array<UpperRun, %d> upper_runs = {{" % len(runs)]
    out += ["    {.start = 0x%05X, .count = %d, .stride = %d, .delta = %d}," % r for r in runs]
    out.append("}};")
    out.append("inline constexpr std::array<UpperSpecial, %d> upper_special = {{" % len(special))
    for c, us in special:
        us = us + [0] * (3 - len(us))
        out.append("    {.from = 0x%05X, .to = {0x%05X, 0x%05X, 0x%05X}}," % (c, us[0], us[1], us[2]))
    out.append("}};")
    return "\n".join(out) + "\n"


def c_string(s):
    out = ""
    for ch in s.encode("utf-8"):
        out += chr(ch) if 32 <= ch < 127 and ch not in (34, 92) else '\\x%02X""' % ch
    return '"' + out + '"'


def check_runs():
    rows = []
    with open("tests/text/android_shaping.txt", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line and not line.startswith("#"):
                head, text, _ = line.split(" | ", 2)
                rows.append((head, text))
    out = ["// Generated by text/tables.py from tests/text/android_shaping.txt (its styles and texts, in its order) for "
           "the", "// device's glyph check; tests/text/shaper_test.cpp holds it to the file. Do not edit.",
           "inline constexpr std::array<CheckRun, %d> check_run_table = {{" % len(rows)]
    out += ["    {.head = %s, .text = %s}," % (c_string(h), c_string(t)) for h, t in rows]
    out.append("}};")
    return "\n".join(out) + "\n"


def digits():
    zeros = []
    for c in range(0x10000):
        if unicodedata.category(chr(c)) == "Nd" and unicodedata.decimal(chr(c)) == 0:
            assert all(unicodedata.category(chr(c + k)) == "Nd" and unicodedata.decimal(chr(c + k)) == k
                       for k in range(10))
            zeros.append(c)
    out = ["// Generated by text/tables.py from CPython %s (Unicode %s): the zero of each run of ten decimal digits (Nd) "
           "in the" % (sys.version.split()[0], unicodedata.unidata_version),
           "// Basic Multilingual Plane, ascending. Do not edit.",
           "inline constexpr std::array<char32_t, %d> digit_zeros = {" % len(zeros)]
    for i in range(0, len(zeros), 8):
        out.append("    " + " ".join("0x%04X," % c for c in zeros[i:i + 8]))
    out.append("};")
    return "\n".join(out) + "\n"


# Other_Lowercase and Other_Uppercase as JDK 17's ConditionalSpecialCasing.isCased lists them, beside Lu, Ll and Lt.
JAVA_OTHER_CASED = [(0x02B0, 0x02B8), (0x02C0, 0x02C1), (0x02E0, 0x02E4), (0x0345, 0x0345), (0x037A, 0x037A),
                    (0x1D2C, 0x1D61), (0x2160, 0x217F), (0x24B6, 0x24E9)]


def case():
    lower, lower_special, title, cased = [], [], [], []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        low = chr(c).lower()
        if low != chr(c):
            if len(low) == 1:
                lower.append((c, ord(low)))
            else:
                lower_special.append((c, [ord(x) for x in low]))
        t = chr(c).title()
        if len(t) == 1 and t != chr(c):
            title.append((c, ord(t)))
        if unicodedata.category(chr(c)) in ("Lu", "Ll", "Lt") or any(a <= c <= b for a, b in JAVA_OTHER_CASED):
            if cased and cased[-1][1] == c - 1:
                cased[-1][1] = c
            else:
                cased.append([c, c])
    out = ["// Generated by text/tables.py from CPython %s (Unicode %s): str.lower() and the simple titlecase of "
           "each" % (sys.version.split()[0], unicodedata.unidata_version),
           "// code point, and the code points Java's final sigma counts as cased. Each run maps start + k * stride "
           "(k < count)", "// to itself + delta. Do not edit."]
    for name, runs in (("lower_runs", runs_of(lower)), ("title_runs", runs_of(title))):
        out.append("inline constexpr std::array<CaseRun, %d> %s = {{" % (len(runs), name))
        out += ["    {.start = 0x%05X, .count = %d, .stride = %d, .delta = %d}," % r for r in runs]
        out.append("}};")
    out.append("inline constexpr std::array<CaseSpecial, %d> lower_special = {{" % len(lower_special))
    for c, us in lower_special:
        us = us + [0] * (3 - len(us))
        out.append("    {.from = 0x%05X, .to = {0x%05X, 0x%05X, 0x%05X}}," % (c, us[0], us[1], us[2]))
    out.append("}};")
    out.append("inline constexpr std::array<CasedRange, %d> cased_ranges = {{" % len(cased))
    out += ["    {.first = 0x%05X, .last = 0x%05X}," % (a, b) for a, b in cased]
    out.append("}};")
    return "\n".join(out) + "\n"


def pyre():
    word, digit = re.compile(r"\w"), re.compile(r"\d")
    words = []
    for c in range(0x110000):
        if not word.match(chr(c)):
            continue
        assert chr(c).isalnum() or c == 0x5F
        if words and words[-1][1] == c - 1:
            words[-1][1] = c
        else:
            words.append([c, c])
    # \d is the decimal digits (Nd) in runs of ten, the plane's those of text/Digits.inc
    zeros = [c for c in range(0x110000) if digit.match(chr(c)) and int(chr(c)) == 0]
    assert all(digit.match(chr(z + k)) and int(chr(z + k)) == k for z in zeros for k in range(10))
    assert sum(1 for c in range(0x110000) if digit.match(chr(c))) == 10 * len(zeros)
    assert [z for z in zeros if z < 0x10000] == [c for c in range(0x10000) if unicodedata.category(chr(c)) == "Nd"
                                                 and unicodedata.decimal(chr(c)) == 0]
    zeros = [z for z in zeros if z >= 0x10000]
    out = ["// Generated by text/tables.py from CPython %s (Unicode %s): what re reads as \\w (str.isalnum() or "
           "\"_\") as" % (sys.version.split()[0], unicodedata.unidata_version),
           "// ranges of code points, and as \\d beyond the Basic Multilingual Plane as the zero of each run of ten "
           "decimal", "// digits (text/Digits.inc holds the plane's), ascending. Do not edit.",
           "inline constexpr std::array<WordRange, %d> word_ranges = {{" % len(words)]
    out += ["    {.first = 0x%05X, .last = 0x%05X}," % (a, b) for a, b in words]
    out.append("}};")
    out.append("inline constexpr std::array<char32_t, %d> astral_digit_zeros = {" % len(zeros))
    for i in range(0, len(zeros), 8):
        out.append("    " + " ".join("0x%05X," % c for c in zeros[i:i + 8]))
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    with open("text/Uppercase.inc", "w") as f:
        f.write(uppercase())
    with open("text/CheckRuns.inc", "w") as f:
        f.write(check_runs())
    with open("text/Digits.inc", "w") as f:
        f.write(digits())
    with open("text/Case.inc", "w") as f:
        f.write(case())
    with open("text/PyRe.inc", "w") as f:
        f.write(pyre())
