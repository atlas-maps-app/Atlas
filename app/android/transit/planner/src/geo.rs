/// cos(latitude) scaled by 65,536, for a latitude in 1e-7 degree.
pub fn cos_e16(lat: i32) -> i64 {
    let tenth = (lat.unsigned_abs() / 1_000_000).min(900) as usize;
    COS_TABLE[tenth] as i64
}

/// Millimetres between two points given in 1e-7 degree, on the plane at their mean latitude.
pub fn distance_mm(lat1: i32, lon1: i32, lat2: i32, lon2: i32) -> u64 {
    let c = cos_e16(((lat1 as i64 + lat2 as i64).div_euclid(2)) as i32);
    let dy = ((lat2 as i64 - lat1 as i64) * 111_195).div_euclid(10_000);
    let dx = (((lon2 as i64 - lon1 as i64) * 111_195).div_euclid(10_000) * c).div_euclid(65_536);
    isqrt_round((dx as i128 * dx as i128 + dy as i128 * dy as i128) as u128)
}

/// The square root, rounded to the nearest whole number (halves up).
fn isqrt_round(n: u128) -> u64 {
    if n == 0 {
        return 0;
    }
    // Newton from above; n is under 2^80 here, so the first guess fits
    let mut x = 1u128 << (128 - n.leading_zeros()).div_ceil(2);
    loop {
        let y = (x + n / x) / 2;
        if y >= x {
            break;
        }
        x = y;
    }
    if (x + 1) * (x + 1) - n <= n - x * x { (x + 1) as u64 } else { x as u64 }
}

/// A place on the map a wish can name.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Area {
    /// Everything within `radius_m` metres of a point.
    Circle { lat: i32, lon: i32, radius_m: u32 },
    /// A box, by its south, west, north and east edges.
    Box { south: i32, west: i32, north: i32, east: i32 },
    /// An outline, as (latitude, longitude) corners; it closes itself. The even-odd rule decides what is inside.
    Outline(Vec<(i32, i32)>),
}

impl Area {
    pub fn contains(&self, lat: i32, lon: i32) -> bool {
        match self {
            Area::Circle { lat: a, lon: o, radius_m } => distance_mm(*a, *o, lat, lon) <= *radius_m as u64 * 1000,
            Area::Box { south, west, north, east } => (*south..=*north).contains(&lat) && (*west..=*east).contains(&lon),
            Area::Outline(ring) => {
                let mut inside = false;
                let n = ring.len();
                for i in 0..n {
                    let (a, b) = (ring[i], ring[(i + 1) % n]);
                    if (a.0 > lat) != (b.0 > lat) {
                        // the edge crosses the point's latitude: on which side of the point?
                        let cross = (b.1 as i128 - a.1 as i128) * (lat as i128 - a.0 as i128) - (lon as i128 - a.1 as i128) * (b.0 as i128 - a.0 as i128);
                        if (cross > 0) == (b.0 > a.0) {
                            inside = !inside;
                        }
                    }
                }
                inside
            }
        }
    }

    /// The latitudes it lies between, to look only at stops that can be inside.
    pub fn latitudes(&self) -> (i32, i32) {
        match self {
            Area::Circle { lat, radius_m, .. } => {
                let reach = (*radius_m as i64 * 10_000_000 / 111_195 + 2).min(i32::MAX as i64) as i32;
                (lat.saturating_sub(reach), lat.saturating_add(reach))
            }
            Area::Box { south, north, .. } => (*south, *north),
            Area::Outline(ring) => (ring.iter().map(|p| p.0).min().unwrap_or(0), ring.iter().map(|p| p.0).max().unwrap_or(-1)),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn distances() {
        // Amsterdam Centraal to Utrecht Centraal: 35 km
        let d = distance_mm(523_789_000, 49_003_000, 520_893_000, 51_100_000);
        assert!((34_900_000..35_400_000).contains(&d), "{d}");
        assert_eq!(distance_mm(1, 2, 1, 2), 0);
        // a tenth of a degree of latitude
        assert_eq!(distance_mm(520_000_000, 0, 521_000_000, 0), 11_119_500);
        // nothing overflows at the ends of the earth
        assert!(distance_mm(-900_000_000, -1_800_000_000, 900_000_000, 1_800_000_000) > 0);
        assert!(distance_mm(i32::MIN, i32::MIN, i32::MAX, i32::MAX) > 0);
    }

    #[test]
    fn roots() {
        for n in [0u128, 1, 2, 3, 4, 6, 7, 99, 100, 101, 1 << 40, (1 << 40) + 12345, u64::MAX as u128, 1 << 79] {
            let r = isqrt_round(n) as u128;
            assert!(r * r <= n + r && n <= r * r + r, "{n} {r}");
        }
    }

    #[test]
    fn areas() {
        let square = Area::Outline(alloc::vec![(0, 0), (0, 10), (10, 10), (10, 0)]);
        assert!(square.contains(5, 5));
        assert!(!square.contains(5, 11));
        assert!(!square.contains(-1, 5));
        let l = Area::Outline(alloc::vec![(0, 0), (0, 10), (4, 10), (4, 4), (10, 4), (10, 0)]);
        assert!(l.contains(2, 8) && l.contains(8, 2) && !l.contains(8, 8));
        assert!(!Area::Outline(Vec::new()).contains(0, 0));
        assert!(Area::Circle { lat: 520_000_000, lon: 50_000_000, radius_m: 1000 }.contains(520_050_000, 50_000_000));
        assert!(!Area::Circle { lat: 520_000_000, lon: 50_000_000, radius_m: 1000 }.contains(520_100_000, 50_000_000));
        assert!(Area::Box { south: 0, west: 0, north: 5, east: 5 }.contains(5, 0));
    }
}
