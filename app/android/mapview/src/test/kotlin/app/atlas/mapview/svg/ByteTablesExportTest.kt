/**
 * The map core's copies of what [SvgFilterRaster] computes (plan-vector K17a), written into the core's sources by the
 * port's own code and checked against them: the core cannot compute them itself (the tables come from Java's pow) or
 * must be held to them on hosts that run no JVM (CI's arm64 runner, the emulator, a phone).
 *
 * - `CP/fx/tables/to_linear.inc` and `to_srgb.inc`: [SvgFilterRaster.Bytes]' two conversion tables, read through its
 *   own `unpremultiplyExact`, a row of 256 bytes a line, a string of hexadecimal digits.
 * - `CP/fx/tables/fields.inc`: the reference hashes of the renders' five screen-wide noise fields at D16's sizes and the
 *   owner's phone's family, each as [Turbulence.fillWebKit] makes it and as the core keeps it (what each filter's next
 *   primitive reads, by [SvgFilterRaster]'s own code), and of the generators' lattices and gradients.
 * - `CP/fx/tables/mat.inc`: the hash of `mat`'s filter on every source pixel and grey, by a transcription of its steps
 *   that this test first holds to [SvgFilterRaster]'s own `mat` over half a million pixels.
 *
 * A file that differs from what this computes fails the test, naming it; `ATLAS_WRITE_TABLES=1` in the environment
 * writes the files instead.
 */
class ByteTablesExportTest {
    private val repo = File(System.getProperty("atlas.repo") ?: "../..")
    private val tables = File(repo, "app/android/mapcore/cpp/fx/tables")
    private val write = System.getenv("ATLAS_WRITE_TABLES") == "1"

    @Test
    fun `the byte tables in the core are SvgFilterRaster's own`() {
        for ((name, linear) in listOf("to_linear" to true, "to_srgb" to false)) {
            val t = ByteArray(256 * 256)
            for (a in 0 until 256) for (c in 0 until 256) {
                // unpremultiplyExact reads the table at a · 256 + c for each channel; a is 0 only where the table is
                val p = SvgFilterRaster.Bytes.unpremultiplyExact((a shl 24) or (c shl 16) or (c shl 8) or c, linear)
                t[a * 256 + c] = ((p shr 16) and 0xFF).toByte()
            }
            val text = buildString {
                append("// Generated by mapview's ByteTablesExportTest from SvgFilterRaster.Bytes.unpremultiplyExact (")
                append(if (linear) "to linear RGB" else "to sRGB").append("): entry a · 256 + c, a row of 256 bytes\n")
                append("// a line in hexadecimal, a row a string. Do not edit: ATLAS_WRITE_TABLES=1 writes it again.\n")
                for (a in 0 until 256) {
                    append('"')
                    for (c in 0 until 256) append("%02x".format(t[a * 256 + c].toInt() and 0xFF))
                    append("\",\n")
                }
            }
            check(File(tables, "$name.inc"), text)
        }
    }

    @Test
    fun `a gradient's length is the square root of its exact sum of squares`() {
        // Turbulence normalises each gradient (gx, gy), multiples of 1/256 of magnitude at most 1, by
        // Math.hypot(gx, gy) in float. Their squares and the sum are exact in double, so the core takes the correctly
        // rounded square root: it must give Math.hypot's float for every pair the generator can draw.
        var differ = 0
        for (nx in -256..255) for (ny in -256..255) {
            if (nx == 0 && ny == 0) continue
            val fx = (nx.toDouble() / 256).toFloat().toDouble()
            val fy = (ny.toDouble() / 256).toFloat().toDouble()
            if (Math.hypot(fx, fy).toFloat() != Math.sqrt(fx * fx + fy * fy).toFloat()) differ++
        }
        assertEquals("pairs whose Math.hypot and square root differ as floats", 0, differ)
    }

    @Test
    fun `the screen-wide fields' hashes in the core are the port's`() {
        val pool = Executors.newFixedThreadPool(Runtime.getRuntime().availableProcessors().coerceIn(1, 8))
        try {
            val text = buildString {
                append("// Generated by mapview's ByteTablesExportTest from the port's Turbulence and SvgFilterRaster: the\n")
                append("// renders' eight screen-wide noise fields (render/amsterdam.py's mat, grain, ripple, glint0, cloudsh,\n")
                append("// leaf; render/closeup.py's crown filter's displacement and tone) at\n")
                append("// D16's sizes and phones', each at its BoardScale density (width / 412) as its filter scale. For each\n")
                append("// generator, the first 8 bytes of the SHA-256 of its lattice selector (514 ints, little-endian) and of\n")
                append("// its gradients (2,048 floats' bits, little-endian); for each field and size, of the noise (fillWebKit's\n")
                append("// packed a r g b ints over the frame, little-endian, rows from the top) and of the bytes the core keeps\n")
                append("// (fx/Fields.hpp: per pixel, the channels its next primitive reads). Do not edit: ATLAS_WRITE_TABLES=1\n")
                append("// writes it again.\n")
                for (f in (FIELDS.map { it.seed } + EXTRA_SEEDS).distinct()) {
                    val t = Turbulence(f)
                    val sel = ByteBuffer.allocate(4 * 514).order(ByteOrder.LITTLE_ENDIAN).also { b -> t.lattice.forEach { b.putInt(it) } }
                    val grads = ByteBuffer.allocate(4 * 2048).order(ByteOrder.LITTLE_ENDIAN)
                    for (g in t.gradientsWebKit) grads.putInt(java.lang.Float.floatToRawIntBits(g))
                    append("ATLAS_LATTICE(%d, 0x%sULL, 0x%sULL)\n".format(f.toInt(), prefix(sel.array()), prefix(grads.array())))
                }
                for (size in SIZES) {
                    val scale = (size.w / 412.0).toFloat()
                    for (field in FIELDS) {
                        val noise = noise(field, size, scale, pool)
                        val kept = kept(field, size, scale, noise, pool)
                        append("ATLAS_FIELD(\"%s\", %d, %d, 0x%08x, \"%s\", 0x%sULL, 0x%sULL)\n".format(
                            size.name, size.w, size.h, java.lang.Float.floatToRawIntBits(scale), field.name,
                            prefix(ints(noise)), prefix(kept),
                        ))
                    }
                }
            }
            check(File(tables, "fields.inc"), text)
        } finally {
            pool.shutdown()
        }
    }

    @Test
    fun `mat's filter in the core is SvgFilterRaster's on every source pixel and grey`() {
        // SvgFilterRaster's own mat (amsterdam.py's definition) over a frame of synthetic source pixels, every alpha
        // with colours up to it, at the field's own greys (read back from the noise cache the raster fills).
        val w = 1080
        val h = 512
        val scale = (1080 / 412.0).toFloat()
        val dir = kotlin.io.path.createTempDirectory("mat").toFile()
        try {
            val cache = TurbulenceCache(dir, maxBytes = 1L shl 30, maxDiskBytes = 1L shl 31)
            val doc = SvgParser.parse(
                "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 412 196\" width=\"412\" height=\"196\"><defs>" +
                    "<filter id=\"mat\" filterUnits=\"userSpaceOnUse\" x=\"0\" y=\"0\" width=\"412\" height=\"196\">" + MAT_PRIMITIVES + "</filter>" +
                    "</defs></svg>",
            )
            val f = doc.filters.getValue("mat")
            val raster = SvgFilterRaster(f, cache)
            assertTrue(raster.prepare(DoubleArray(4) { f.region[it].toDouble() }, scale.toDouble(), scale.toDouble(), SvgFilterRaster.Rect(0, 0, w, h)))
            val sr = raster.sourceRect
            assertTrue("the source is the frame: $sr", sr.left == 0 && sr.top == 0 && sr.width == w && sr.height == h)
            val source = IntArray(w * h) { i ->
                val a = i % 256
                val c = (i / 256) % (a + 1)
                (a shl 24) or (c shl 16) or (((c * 7) % (a + 1)) shl 8) or ((c * 13) % (a + 1))
            }
            val out = IntArray(w * h)
            raster.run(source, out, bands = SvgFilterRaster.WORKERS)
            val stepped = cache.kept().single { it.steps.isNotEmpty() }
            val grey = IntArray(w * h)
            cache.fill(stepped, 0, 0, w, h, grey, map = { error("every tile was kept by the run") })
            cache.close()
            var differ = 0
            for (i in 0 until w * h) if (matPixel(source[i], (grey[i] shr 16) and 0xFF) != out[i]) differ++
            assertEquals("pixels where the transcription is not SvgFilterRaster's mat", 0, differ)
        } finally {
            dir.deleteRecursively()
        }
        // every source pixel (a, c, c, c) and grey: the alpha for each a, then the colour for each a, c and g
        val all = ByteArray(256 + 256 * 256 * 256)
        for (a in 0 until 256) all[a] = (matPixel(a shl 24, 0) ushr 24).toByte()
        for (a in 0 until 256) for (c in 0 until 256) for (g in 0 until 256) {
            all[256 + (a * 256 + c) * 256 + g] = ((matPixel((a shl 24) or (c shl 16) or (c shl 8) or c, g) shr 16) and 0xFF).toByte()
        }
        val text = "// Generated by mapview's ByteTablesExportTest: the first 8 bytes of the SHA-256 of mat's filter on every source\n" +
            "// pixel (a, c, c, c) and grey g, as SvgFilterRaster computes it: the result's alpha for each a, then its colour for\n" +
            "// each a, c and g in that order. Do not edit: ATLAS_WRITE_TABLES=1 writes it again.\n" +
            "ATLAS_MAT_PIXEL(0x${prefix(all)}ULL)\n"
        check(File(tables, "mat.inc"), text)
    }

    /**
     * `mat`'s steps after its colour matrix as SvgFilterRaster takes them, on a source pixel [p] (premultiplied sRGB)
     * and the matrix's grey [g]: the source drawn into linear RGB, the arithmetic composite (k1 .2, k2 .9) truncated
     * as WebKit's NEON code does, the result corrected to valid premultiplied colour, `in` the source's alpha, and the
     * output written as premultiplied sRGB.
     */
    private fun matPixel(p: Int, g: Int): Int {
        fun arithmetic(c: Int, i2: Int): Int {
            val k1 = 0.2f / 255f
            val i1 = c.toFloat()
            var r = i1 * 0.9f
            r += i2.toFloat() * 0f
            r += (i1 * i2.toFloat()) * k1
            return if (r <= 0f) 0 else minOf(r.toInt(), 255)
        }
        val src = SvgFilterRaster.Bytes.srgbToLinearPremultiplied(p)
        val ta = arithmetic(src ushr 24, 255)
        val tr = minOf(arithmetic((src shr 16) and 0xFF, g), ta)
        val tg = minOf(arithmetic((src shr 8) and 0xFF, g), ta)
        val tb = minOf(arithmetic(src and 0xFF, g), ta)
        val q = SvgFilterRaster.Bytes.scale((ta shl 24) or (tr shl 16) or (tg shl 8) or tb, p ushr 24)
        return SvgFilterRaster.Bytes.premultiply(SvgFilterRaster.Bytes.unpremultiplyExact(q, false))
    }

    /** The noise of [field] over a [size] frame at [scale], as SvgFilterRaster's turbulence makes it for its consumer. */
    private fun noise(field: Field, size: Size, scale: Float, pool: java.util.concurrent.ExecutorService): IntArray {
        val out = IntArray(size.w * size.h)
        val t = Turbulence.of(field.seed)
        val inv = 1f / scale
        val bands = 32
        pool.invokeAll((0 until bands).map { k ->
            Callable {
                val y0 = size.h * k / bands
                val y1 = size.h * (k + 1) / bands
                t.fillWebKit(0, y0, size.w, y1 - y0, inv, inv, field.baseX, field.baseY, field.octaves, true, field.need, out, y0 * size.w, size.w)
            }
        }).forEach { it.get() }
        return out
    }

    /**
     * The bytes the core keeps of [field] (per pixel, its channels in order), by SvgFilterRaster's own code: `mat`'s
     * grey as its colour matrix leaves it (linear RGB, read back from the noise cache the raster fills), the grain's
     * filter result (premultiplied sRGB grey and alpha), the ripple's red and green as the displacement reads them,
     * and for the glints and the cloud shadows the red their colour matrices read (the noise premultiplied, then
     * unpremultiplied, as a matrix reads its input).
     */
    private fun kept(field: Field, size: Size, scale: Float, noise: IntArray, pool: java.util.concurrent.ExecutorService): ByteArray {
        val n = size.w * size.h
        return when (field.keep) {
            Keep.RED_GREEN -> ByteArray(2 * n) { i -> ((noise[i / 2] shr (if (i % 2 == 0) 16 else 8)) and 0xFF).toByte() }
            Keep.MATRIX_RED -> ByteArray(n) { i ->
                ((SvgFilterRaster.Bytes.unpremultiply(SvgFilterRaster.Bytes.premultiply(noise[i])) shr 16) and 0xFF).toByte()
            }
            Keep.MATRIX_GREY -> {
                val dir = kotlin.io.path.createTempDirectory("fields").toFile()
                try {
                    val cache = TurbulenceCache(dir, maxBytes = 1L shl 30, maxDiskBytes = 1L shl 31)
                    run(field, size, scale, cache)
                    val stepped = cache.kept().single { it.steps.isNotEmpty() }
                    val px = IntArray(n)
                    cache.fill(stepped, 0, 0, size.w, size.h, px, map = { error("every tile was kept by the run") })
                    cache.close()
                    ByteArray(n) { i ->
                        check(px[i] ushr 24 == 255 && (px[i] shr 16) and 0xFF == px[i] and 0xFF) { "mat's grey is opaque and grey" }
                        ((px[i] shr 16) and 0xFF).toByte()
                    }
                } finally {
                    dir.deleteRecursively()
                }
            }
            Keep.RESULT_GREY_ALPHA -> {
                val out = run(field, size, scale, null)
                ByteArray(2 * n) { i -> (if (i % 2 == 0) (out[i / 2] shr 16) and 0xFF else out[i / 2] ushr 24).toByte() }
            }
        }
    }

    /** [field]'s filter (its turbulence and colour matrix) run by SvgFilterRaster over the frame; its result. */
    private fun run(field: Field, size: Size, scale: Float, cache: TurbulenceCache?): IntArray {
        val frameW = Math.ceil(size.w / (size.w / 412.0) - 1e-6).toInt()
        val frameH = Math.ceil(size.h / (size.w / 412.0) - 1e-6).toInt()
        val doc = SvgParser.parse(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 $frameW $frameH\" width=\"$frameW\" height=\"$frameH\"><defs>" +
                "<filter id=\"f\" filterUnits=\"userSpaceOnUse\" x=\"0\" y=\"0\" width=\"$frameW\" height=\"$frameH\">${field.primitives}</filter>" +
                "</defs></svg>",
        )
        val raster = SvgFilterRaster(doc.filters.getValue("f"), cache)
        val f = doc.filters.getValue("f")
        val region = DoubleArray(4) { f.region[it].toDouble() }
        val s = scale.toDouble()
        assertTrue(raster.prepare(region, s, s, SvgFilterRaster.Rect(0, 0, size.w, size.h)))
        val o = raster.outputRect
        assertTrue("the filter covers the frame: ${o}", o.left == 0 && o.top == 0 && o.right == size.w && o.bottom == size.h)
        val out = IntArray(o.width * o.height)
        raster.run(IntArray(0), out, bands = SvgFilterRaster.WORKERS)
        return out
    }

    /** Fails naming [file] when it differs from [text], or writes it when asked to. */
    private fun check(file: File, text: String) {
        if (write) {
            file.parentFile.mkdirs()
            if (!file.isFile || file.readText() != text) file.writeText(text)
            println("wrote ${file.path}")
            return
        }
        assertTrue("${file.path} is missing: run this test with ATLAS_WRITE_TABLES=1", file.isFile)
        assertTrue("${file.path} differs from what the port computes: run this test with ATLAS_WRITE_TABLES=1", file.readText() == text)
    }

    private fun ints(v: IntArray): ByteArray = ByteBuffer.allocate(4 * v.size).order(ByteOrder.LITTLE_ENDIAN).also { b -> v.forEach { b.putInt(it) } }.array()

    private fun prefix(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).take(8).joinToString("") { "%02x".format(it.toInt() and 0xFF) }

    /** What the core keeps of a field's pixel. */
    private enum class Keep { MATRIX_GREY, RESULT_GREY_ALPHA, RED_GREEN, MATRIX_RED }

    /** A screen-wide field: its turbulence, the channels its consumer reads, its filter's primitives up to its matrix. */
    private class Field(
        val name: String,
        val seed: Float,
        val baseX: Float,
        val baseY: Float,
        val octaves: Int,
        val need: Int,
        val keep: Keep,
        val primitives: String,
    )

    private class Size(val name: String, val w: Int, val h: Int)

    companion object {
        /** `mat`'s primitives as amsterdam.py writes them. */
        private const val MAT_PRIMITIVES =
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\".16 .75\" numOctaves=\"2\" seed=\"13\"/>" +
                "<feColorMatrix type=\"matrix\" values=\".33 .33 .33 0 0  .33 .33 .33 0 0  .33 .33 .33 0 0  0 0 0 0 1\" result=\"g\"/>" +
                "<feComposite in=\"SourceGraphic\" in2=\"g\" operator=\"arithmetic\" k1=\".2\" k2=\".9\" k3=\"0\" k4=\"0\" result=\"t\"/>" +
                "<feComposite in=\"t\" in2=\"SourceAlpha\" operator=\"in\"/>"

        /**
         * The renders' screen-wide fields (render/amsterdam.py: `mat`, `grain`, `ripple`, `glint0` at map pitches, `cloudsh`;
         * render/closeup.py: the crown filter's `n` and `m`).
         */
        private val FIELDS = listOf(
            Field("mat", 13f, 0.16f, 0.75f, 2, 15, Keep.MATRIX_GREY,
                "<feTurbulence type=\"fractalNoise\" baseFrequency=\".16 .75\" numOctaves=\"2\" seed=\"13\"/>" +
                    "<feColorMatrix type=\"matrix\" values=\".33 .33 .33 0 0  .33 .33 .33 0 0  .33 .33 .33 0 0  0 0 0 0 1\"/>"),
            Field("grain", 8f, 0.9f, 0.9f, 1, 15, Keep.RESULT_GREY_ALPHA,
                "<feTurbulence type=\"fractalNoise\" baseFrequency=\".9\" numOctaves=\"1\" seed=\"8\"/><feColorMatrix type=\"saturate\" values=\"0\"/>"),
            Field("ripple", 11f, 0.012f, 0.26f, 2, 3, Keep.RED_GREEN, ""),
            Field("glints", 5f, 0.02f, 0.3f, 2, 15, Keep.MATRIX_RED, ""),
            Field("cloud_shadows", 23f, 0.0026f, 0.0058f, 3, 15, Keep.MATRIX_RED, ""),
            // closeup.py's crown filter: its displacement's red and green, and its tone matrix's red
            Field("crown", 5f, 0.15f, 0.15f, 2, 3, Keep.RED_GREEN, ""),
            Field("crown_tone", 2f, 0.42f, 0.42f, 2, 15, Keep.MATRIX_RED, ""),
            // amsterdam.py's leaf filter on the reflected trees: its displacement's red and green
            Field("leaf", 3f, 0.55f, 0.55f, 2, 3, Keep.RED_GREEN, ""),
        )

        /** Other seeds the renders' filters use (K17's per-tree and clamped fields), whose generators are checked too. */
        private val EXTRA_SEEDS = listOf(2f, 3f, 4f, 9f, 17f, 31f)

        /**
         * D16's sizes, and the owner's phone's family (the Pixel 10 and 10 Pro at full resolution, the Pro XL being S4,
         * and the Pros at their default "high resolution"), until its VK facts name its own.
         */
        private val SIZES = listOf(
            Size("S1", 1080, 2400), Size("S2", 1080, 2340), Size("S3", 1440, 3120), Size("S4", 1344, 2992),
            Size("pixel10", 1080, 2424), Size("pixel10pro", 1280, 2856), Size("pixel10pro-high", 960, 2142),
            Size("pixel10proxl-high", 1008, 2244),
        )
    }

    @Test
    fun `the fields are the renders' own definitions`() {
        // The parameters above are amsterdam.py's: its filters must still say so.
        val py = File(repo, "render/amsterdam.py").readText()
        for (s in listOf(
            MAT_PRIMITIVES,
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\".16 .75\" numOctaves=\"2\" seed=\"13\"/><feColorMatrix type=\"matrix\" values=\".33 .33 .33 0 0  .33 .33 .33 0 0  .33 .33 .33 0 0  0 0 0 0 1\"",
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\".9\" numOctaves=\"1\" seed=\"8\"/><feColorMatrix type=\"saturate\" values=\"0\"/>",
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\"0.012 0.26\" numOctaves=\"2\" seed=\"11\" result=\"n\"/><feDisplacementMap in=\"SourceGraphic\" in2=\"n\" scale=\"%.1f\" xChannelSelector=\"R\" yChannelSelector=\"G\"/>",
            "if zz is None: fx, fy = 0.02, 0.3",
            "numOctaves=\"2\" seed=\"%d\"/><feColorMatrix type=\"matrix\" values=\"0 0 0 0 %.2f  0 0 0 0 %.2f  0 0 0 0 %.2f  11 0 0 0 -6.9\"/>",
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\"0.0026 0.0058\" numOctaves=\"3\" seed=\"23\"/><feColorMatrix type=\"matrix\" values=\"0 0 0 0 0.16  0 0 0 0 0.19  0 0 0 0 0.32  7 0 0 0 %.2f\"/>",
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\".55\" numOctaves=\"2\" seed=\"3\" result=\"n\"/><feDisplacementMap in=\"SourceGraphic\" in2=\"n\" scale=\"2.6\" xChannelSelector=\"R\" yChannelSelector=\"G\"/>",
        )) assertTrue("amsterdam.py no longer holds: $s", py.contains(s))
        val closeup = File(repo, "render/closeup.py").readText()
        for (s in listOf(
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\".15\" numOctaves=\"2\" seed=\"5\" result=\"n\"/>",
            "<feDisplacementMap in=\"SourceGraphic\" in2=\"n\" scale=\"10\" xChannelSelector=\"R\" yChannelSelector=\"G\" result=\"d\"/>",
            "<feTurbulence type=\"fractalNoise\" baseFrequency=\".42\" numOctaves=\"2\" seed=\"2\" result=\"m\"/>",
            "<feColorMatrix in=\"m\" type=\"matrix\" values=\"1 0 0 0 .5  1 0 0 0 .5  1 0 0 0 .5  0 0 0 0 1\" result=\"tone\"/>",
        )) assertTrue("closeup.py no longer holds: $s", closeup.contains(s))
    }
}
